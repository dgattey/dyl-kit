import DylToolSupport
import Foundation

/// Thin forge workflows. Each one checks out, sets up the toolchain, passes secrets in as environment variables and
/// runs one DylKit command; the logic lives in `devkit` and `release-kit` so another forge only needs new wrappers.
/// `devkit ci sync` writes them and `release-kit check` fails when a committed copy drifts from this source.
public enum CIWrappers {
    public enum Forge: String, CaseIterable, Sendable {
        case github
    }

    public struct Wrapper: Sendable, Equatable {
        public let path: String
        public let contents: String
    }

    public static let releaseWorkflowPath = ".github/workflows/release.yml"

    public static func render(_ forge: Forge, workspace: Workspace) -> [Wrapper] {
        switch forge {
        case .github: return github(workspace: workspace)
        }
    }

    /// The paths that trigger a release: the manifest's inputs plus the release wrapper itself.
    public static func releaseTriggerPaths(workspace: Workspace) -> [String] {
        workspace.manifest.release.inputs + [releaseWorkflowPath]
    }

    private static let header = """
        # Generated by `./run dev ci sync` from DylKit's CIWrappers. Change the template there, then re-sync.
        """

    private static let xcode = """
              - name: Select Xcode
                run: sudo xcode-select -s /Applications/Xcode_26.5.app/Contents/Developer
        """

    private static func github(workspace: Workspace) -> [Wrapper] {
        let paths = releaseTriggerPaths(workspace: workspace).map { "      - '\($0)'" }.joined(separator: "\n")
        let verify = """
            \(header)
            name: verify

            on:
              pull_request:
              push:
                branches: [main]

            concurrency:
              group: verify-${{ github.ref }}
              cancel-in-progress: true

            jobs:
              verify:
                runs-on: macos-26
                steps:
                  - uses: actions/checkout@v4
            \(xcode)
                  - name: Install SwiftLint
                    run: command -v swiftlint >/dev/null || brew install swiftlint
                  - name: Verify
                    run: ./run dev verify

            """
        let release = """
            \(header)
            name: release

            on:
              push:
                branches: [main]
                paths:
            \(paths)
              workflow_dispatch:
                inputs:
                  release_type:
                    description: 'Bump type; auto reads the merged PR''s Release info checkbox'
                    required: false
                    default: auto
                    type: choice
                    options: [auto, patch, minor, major]

            permissions:
              contents: write

            concurrency:
              group: release
              cancel-in-progress: false

            jobs:
              release:
                runs-on: macos-26
                steps:
                  - uses: actions/checkout@v4
                    with:
                      fetch-depth: 0
            \(xcode)
                  - name: Plan the version
                    env:
                      RELEASE_TYPE: ${{ inputs.release_type }}
                    run: ./run release version --type "${RELEASE_TYPE:-auto}"
                  - name: Bundle
                    run: ./run release bundle
                  - name: Sign
                    run: ./run release sign
                  - name: Appcast
                    env:
                      SPARKLE_ED_PRIVATE_KEY_BASE64: ${{ secrets.SPARKLE_ED_PRIVATE_KEY_BASE64 }}
                    run: ./run release appcast
                  - name: Check
                    run: ./run release check
                  - name: Publish
                    run: |
                      git config user.name "github-actions[bot]"
                      git config user.email "github-actions[bot]@users.noreply.github.com"
                      ./run release publish
                  - name: Check the live site
                    run: ./run release check --live --wait 900

            """
        let prCheck = """
            \(header)
            name: pr-check

            on:
              pull_request:
                types: [opened, edited, reopened, synchronize]

            jobs:
              release-info:
                runs-on: ubuntu-latest
                container: swift:6.2-noble
                steps:
                  - uses: actions/checkout@v4
                  - name: Check the Release info checkbox
                    env:
                      PR_BODY: ${{ github.event.pull_request.body }}
                    run: |
                      printf '%s' "$PR_BODY" > "$RUNNER_TEMP/pr-body.md"
                      ./run release pr-check --body-file "$RUNNER_TEMP/pr-body.md"

            """
        return [
            Wrapper(path: ".github/workflows/verify.yml", contents: verify),
            Wrapper(path: releaseWorkflowPath, contents: release),
            Wrapper(path: ".github/workflows/pr-check.yml", contents: prCheck),
        ]
    }
}
